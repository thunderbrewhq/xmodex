FMOD_RESULT DSPPitchShift::createInternal() {
    FMOD_RESULT result;

    Plugin::init();

    for (int32_t i = 0; i < DSP_PITCHSHIFT_COSTABSIZE; i++) {
        this->mCosTab[i] = FMOD_COS(FMOD_PI_2 * static_cast<float>(i) / static_cast<float>(DSP_PITCHSHIFT_COSTABSIZE));
    }

    this->mOverlap = 4;
    this->mPitchShift = nullptr;
    this->mPitch = 1.0f;

    for (int32_t i = 0; i < this->mDescription.numparameters; i++) {
        result = this->setParameter(i, this->mDescription.paramdesc[i].defaultval);
        if (result != FMOD_OK) {
            return result;
        }
    }

    return FMOD_OK;
}

FMOD_RESULT DSPPitchShift::releaseInternal() {
    if (this->mPitchShift) {
        FMOD_Memory_Free(this->mPitchShift);
        this->mPitchShift = nullptr;
    }

    return FMOD_OK;
}

FMOD_RESULT DSPPitchShift::resetInternal() {
    if (this->mPitchShift) {
        for (int32_t i = 0; i < this->mChannels; i++) {
            this->mPitchShift[i].smbInit();
            this->mPitchShift[i].mCosTab = this->mCosTab;
        }
    }

    return FMOD_OK;
}

FMOD_RESULT DSPPitchShift::readInternal(float* inbuffer, float* outbuffer, uint32_t length, int32_t inchannels, int32_t outchannels) {
    if (inchannels > this->mChannels || !this->mPitchShift) {
        FMOD_memcpy(outbuffer, inbuffer, length * outchannels * sizeof(float));
        return FMOD_OK;
    }

    for (int32_t i = 0; i < inchannels; i++) {
        this->mPitchShift[i].mFFTFrameSize = this->mFFTSize;
        this->mPitchShift[i].mFFTFrameBits = this->mFFTFrameBits;
        this->mPitchShift[i].smbPitchShift(this->mPitch, length, this->mOverlap, static_cast<float>(this->mOutputRate), inbuffer, outbuffer, i, inchannels);
    }

    return FMOD_OK;
}

FMOD_RESULT DSPPitchShift::setParameterInternal(int32_t index, float value) {
    FMOD_RESULT result;
    int32_t oldchannels;
    int32_t oldfftsize;
    int32_t oldoverlap;
    float oldpitch;
    bool done_lock = false;

    oldchannels = this->mChannels;
    oldfftsize = this->mFFTSize;
    oldpitch = this->mPitch;
    oldoverlap = this->mOverlap;

    switch (index) {
    case FMOD_DSP_PITCHSHIFT_PITCH: {
        this->mPitch = value;
        if (this->mPitch == 0.0f) {
            this->mPitch = 1.0f;
        }
        break;
    }
    case FMOD_DSP_PITCHSHIFT_FFTSIZE: {
        if (value > 4096) {
            this->mFFTSize = 4096;
        } else {
            int32_t nextfftsize = 256;
            while (nextfftsize <= 4096) {
                if (value <= nextfftsize) {
                    this->mFFTSize = nextfftsize;
                    break;
                }
                nextfftsize <<= 1;
            }
        }
        if (oldfftsize != this->mFFTSize) {
            this->mSystem->lockDSP();
            done_lock = true;
        }
        break;
    }
    case FMOD_DSP_PITCHSHIFT_OVERLAP: {
        this->mOverlap = 4;
        if (this->mOverlap < 0) {
            this->mOverlap = 0;
        }
        if (oldoverlap != this->mOverlap) {
            this->mSystem->lockDSP();
            done_lock = true;
        }
        break;
    }
    case FMOD_DSP_PITCHSHIFT_MAXCHANNELS: {
        this->mMaxChannels = static_cast<int32_t>(value);
        break;
    }
    }

    result = this->mSystem->getSoftwareFormat(
        &this->mOutputRate,
        nullptr,
        &this->mChannels,
        nullptr,
        nullptr,
        nullptr);
    if (result != FMOD_OK) {
        if (done_lock) {
            this->mSystem->unlockDSP();
        }
        return result;
    }
    if (this->mMaxChannels) {
        this->mChannels = this->mMaxChannels;
        if (oldchannels != this->mChannels) {
            this->mSystem->lockDSP();
            done_lock = true;
        }
    }

    if (oldfftsize != this->mFFTSize || oldoverlap != this->mOverlap) {
        float* wintab = NULL;
        int32_t wtabsize = 0;
        bool window_parity = false;

        if (!this->mPitchShift) {
            return FMOD_ERR_INVALID_HANDLE;
        }

        switch (this->mFFTSize) {
        case 256:
            wintab = vwin1024;
            wtabsize = 513;
            window_parity = false;
            break;
        case 512:
            wintab = vwin1024;
            wtabsize = 513;
            window_parity = false;
            break;
        case 1024:
            wintab = vwin1024;
            wtabsize = 513;
            window_parity = true;
            break;
        case 2048:
            wintab = vwin1024;
            wtabsize = 513;
            window_parity = false;
            break;
        case 4096:
            wintab = vwin1024;
            wtabsize = 513;
            window_parity = false;
            break;
        }

        int32_t ws2m1 = 2 * (wtabsize - 1);
        float ws2m1ratio = static_cast<float>(ws2m1) / static_cast<float>(this->mFFTSize);
        float window_factor = FMOD_SQRT(static_cast<float>(this->mFFTSize * 0.25f * this->mOverlap));

        for (int k = 0; k < this->mFFTSize; k++) {
            if (window_parity) {
                if (k >= wtabsize) {
                    this->mWindow[k] = wintab[ws2m1 - k];
                } else {
                    this->mWindow[k] = wintab[k];
                }
            } else {
                float ktabpos;
                ktabpos = k * ws2m1ratio;
                int32_t k_a;
                int32_t k_next;

                if (ktabpos > static_cast<float>(wtabsize - 1)) {
                    ktabpos = ws2m1 - ktabpos;
                    k_next = -1;
                } else {
                    k_next = +1;
                }

                k_a = static_cast<int32_t>(ktabpos);
                float win_a = wintab[k_a];

                if (static_cast<float>(k_a) != ktabpos) {
                    float win_b = wintab[k_a + k_next];
                    this->mWindow[k] = win_a + (ktabpos - static_cast<float>(k_a)) * (win_b - win_a);
                } else {
                    this->mWindow[k] = win_a;
                }
            }
            this->mWindow[k] /= window_factor;
        }
        for (int32_t i = 0; i < this->mChannels; i++) {
            this->mPitchShift[i].mWindow = this->mWindow;
        }
        this->reset();
    }

    if (this->mChannels != oldchannels || !this->mPitchShift) {
        if (this->mPitchShift) {
            FMOD_Memory_Free(this->mPitchShift);
        }

        this->mPitchShift = static_cast<DSPPitchShiftSMB*>(FMOD_Memory_Alloc(sizeof(DSPPitchShiftSMB) * this->mChannels));
        if (!this->mPitchShift) {
            if (done_lock) {
                this->mSystem->unlockDSP();
            }
            return FMOD_ERR_MEMORY;
        }

        for (int32_t i = 0; i < this->mChannels; i++) {
            this->mPitchShift[i].smbInit();
            this->mPitchShift[i].mWindow = this->mWindow;
            this->mPitchShift[i].mCosTab = this->mCosTab;
        }
    }

    for (int32_t i = 0; i < this->mChannels; i++) {
        this->mPitchShift[i].mPitchRatioFromLast = this->mPitch / oldpitch;
        if (oldpitch != this->mPitch) {
            this->mPitchShift[i].setResetPhaseFlag();
        }
    }

    int32_t bitslength = this->mFFTSize;

    this->mFFTFrameBits = 0;
    while (bitslength > 1) {
        bitslength >>= 1;
        this->mFFTFrameBits++;
    }

    if (done_lock) {
        this->mSystem->unlockDSP();
    }

    return FMOD_OK;
}

FMOD_RESULT DSPPitchShift::getParameterInternal(int32_t index, float* value, char* valuestr) {
    switch (index) {
    case FMOD_DSP_PITCHSHIFT_PITCH: {
        if (value) {
            *value = this->mPitch;
        }
        if (valuestr) {
            sprintf(valuestr, "%.02f", this->mPitch);
        }
        break;
    }
    case FMOD_DSP_PITCHSHIFT_FFTSIZE: {
        if (value) {
            *value = static_cast<float>(this->mFFTSize);
        }
        if (valuestr) {
            sprintf(valuestr, "%d", this->mFFTSize);
        }
        break;
    }
    case FMOD_DSP_PITCHSHIFT_OVERLAP: {
        if (value) {
            *value = static_cast<float>(this->mOverlap);
        }
        if (valuestr) {
            sprintf(valuestr, "%d", this->mOverlap);
        }
        break;
    }
    case FMOD_DSP_PITCHSHIFT_MAXCHANNELS: {
        if (value) {
            *value = static_cast<float>(this->mMaxChannels);
        }
        if (valuestr) {
            sprintf(valuestr, "%d", this->mMaxChannels);
        }
        break;
    }
    }

    return FMOD_OK;
}

